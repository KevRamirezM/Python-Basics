#Conditional expressions are a one line shortcut for the if-else statement or ternary operator print or

# Even or Odd Number

num = 6
print("Even" if num % 2 == 0 else "Odd")

# Maximum or minimum number

a = 6
b = 7
max_num = a if a > b else b
min_num = a if a < b else b
print(max_num)
print(min_num)

# Adult or Child

age = 18
status = "Adult" if age >= 18 else "Child"
print(status)

# Temperature of the weather

temperature = 20
weather = "HOT" if temperature > 20 else "COLD"
print(weather)

